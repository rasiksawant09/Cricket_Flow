import { createContext } from "react";
import type { Dispatch, SetStateAction } from "react";
import type { CricketTournament } from "../models/CricketTournament";
import type { CricketTournamentPlayer } from "../models/CricketTournamentPlayer";
import type { CricketTournamentRule } from "../models/CricketTournamentRule";
import type { CricketTournamentTeam } from "../models/CricketTournamentTeam";
import type { CricketTournamentStanding } from "../models/CricketTournamentStanding";
import type { CricketTeam } from "../models/CricketTeam";
import type { CricketPlayer } from "../models/CricketPlayer";
import type { TournamentLeaderboards } from "../services/interfaces/IStatisticsService";
import type { NewTournamentPlayerDetails } from "../services/interfaces/ITournamentRegistrationService";
import type { BulkPlayerRegistrationOutcome } from "../services/interfaces/ITournamentRegistrationService";

export interface TournamentContextValue {
  tournaments: CricketTournament[];
  currentTournament: CricketTournament | null;
  tournamentTeams: CricketTournamentTeam[];
  tournamentPlayers: CricketTournamentPlayer[];
  masterTeams: CricketTeam[];
  masterPlayers: CricketPlayer[];
  setTournaments: Dispatch<SetStateAction<CricketTournament[]>>;
  setCurrentTournament: Dispatch<SetStateAction<CricketTournament | null>>;
  setTournamentTeams: Dispatch<SetStateAction<CricketTournamentTeam[]>>;
  setTournamentPlayers: Dispatch<SetStateAction<CricketTournamentPlayer[]>>;
  loadMasterTeams(): Promise<Result<CricketTeam[]>>;
  loadMasterPlayers(): Promise<Result<CricketPlayer[]>>;
  loadTournaments(): Promise<Result<CricketTournament[]>>;
  loadTournament(tournamentId: string): Promise<Result<CricketTournament>>;
  loadTournamentTeams(tournamentId: string): Promise<Result<CricketTournamentTeam[]>>;
  loadTournamentPlayers(tournamentId: string): Promise<Result<CricketTournamentPlayer[]>>;
  loadTournamentStandings(tournamentId: string): Promise<Result<CricketTournamentStanding[]>>;
  loadTournamentLeaderboards(tournamentId: string): Promise<Result<TournamentLeaderboards>>;
  createTournament(tournament: CricketTournament): Promise<Result<CricketTournament>>;
  updateTournament(tournament: CricketTournament): Promise<Result<CricketTournament>>;
  setTournamentStatus(tournamentId: string, statusCode: NonNullable<CricketTournament["statuscode"]>): Promise<Result<CricketTournament>>;
  activateTournament(tournamentId: string): Promise<Result<CricketTournament>>;
  completeTournament(tournamentId: string): Promise<Result<CricketTournament>>;
  archiveTournament(tournamentId: string): Promise<Result<CricketTournament>>;
  createTournamentRule(rule: CricketTournamentRule): Promise<Result<CricketTournamentRule>>;
  updateTournamentRule(rule: CricketTournamentRule): Promise<Result<CricketTournamentRule>>;
  setTournamentRuleEnabled(ruleId: string, enabled: boolean): Promise<Result<CricketTournamentRule>>;
  registerTeam(team: CricketTournamentTeam): Promise<Result<CricketTournamentTeam>>;
  createAndRegisterTeam(tournamentId: string, team: CricketTeam, groupName?: string | null, seedNumber?: number | null): Promise<Result<CricketTournamentTeam>>;
  updateTournamentTeam(team: CricketTeam, registration: CricketTournamentTeam): Promise<Result<CricketTournamentTeam>>;
  removeTournamentTeam(registrationId: string): Promise<Result<void>>;
  createMasterTeam(team: CricketTeam): Promise<Result<CricketTeam>>;
  updateMasterTeam(team: CricketTeam): Promise<Result<CricketTeam>>;
  deleteMasterTeam(teamId: string): Promise<Result<void>>;
  createMasterPlayer(player: CricketPlayer): Promise<Result<CricketPlayer>>;
  updateMasterPlayer(player: CricketPlayer): Promise<Result<CricketPlayer>>;
  deleteMasterPlayer(playerId: string): Promise<Result<void>>;
  createAndRegisterPlayer(player: CricketPlayer, details: NewTournamentPlayerDetails): Promise<Result<CricketTournamentPlayer>>;
  updateTournamentPlayer(player: CricketTournamentPlayer): Promise<Result<CricketTournamentPlayer>>;
  removeTournamentPlayer(registrationId: string): Promise<Result<void>>;
  registerPlayer(player: CricketTournamentPlayer): Promise<Result<CricketTournamentPlayer>>;
  registerPlayers(tournamentId: string, teamId: string, playerIds: readonly string[]): Promise<Result<BulkPlayerRegistrationOutcome>>;
  assignCaptain(player: CricketTournamentPlayer): Promise<Result<CricketTournamentPlayer>>;
  assignViceCaptain(player: CricketTournamentPlayer): Promise<Result<CricketTournamentPlayer>>;
}

export const TournamentContext = createContext<TournamentContextValue | undefined>(undefined);
